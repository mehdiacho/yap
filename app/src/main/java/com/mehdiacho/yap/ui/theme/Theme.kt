/** Brand-extended colors that Material 3's ColorScheme has no slot for. */
data class YapExtendedColors(
  val recording: Color,
  val onRecording: Color,
  val refined: Color,
  val refinedContainer: Color,
  val onRefinedContainer: Color,
  val offline: Color,
  val offlineContainer: Color,
  val onOfflineContainer: Color,
)

private val LightExtended = YapExtendedColors(
  recording = RecordingLight,
  onRecording = OnRecordingLight,
  refined = RefinedLight,
  refinedContainer = RefinedContainerLight,
  onRefinedContainer = OnRefinedContainerLight,
  offline = OfflineLight,
  offlineContainer = OfflineContainerLight,
  onOfflineContainer = OnOfflineContainerLight,
)

private val DarkExtended = YapExtendedColors(
  recording = RecordingDark,
  onRecording = OnRecordingDark,
  refined = RefinedDark,
  refinedContainer = RefinedContainerDark,
  onRefinedContainer = OnRefinedContainerDark,
  offline = OfflineDark,
  offlineContainer = OfflineContainerDark,
  onOfflineContainer = OnOfflineContainerDark,
)

val LocalYapExtendedColors = staticCompositionLocalOf { LightExtended }

/** Accessor object — use `YapTheme.extended.recording`, etc. Coexists with the composable below. */
object YapTheme {
  val extended: YapExtendedColors
    @Composable @ReadOnlyComposable get() = LocalYapExtendedColors.current
}

@Composable
fun YapTheme(
  darkTheme: Boolean = isSystemInDarkTheme(),
  // Brand-consistent by default. Dynamic color (Material You) is opt-in via Settings.
  dynamicColor: Boolean = false,
  content: @Composable () -> Unit,
) {
  val colorScheme =
    when {
      dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
        val context = LocalContext.current
        if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
      }
      darkTheme -> DarkColorScheme
      else -> LightColorScheme
    }
  val extended = if (darkTheme) DarkExtended else LightExtended

  CompositionLocalProvider(LocalYapExtendedColors provides extended) {
    MaterialTheme(colorScheme = colorScheme, typography = Typography, content = content)
  }
}
